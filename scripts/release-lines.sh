#!/usr/bin/env bash
# Generates the release-line pages and the module availability data from
# "releases" in _config.yml. scripts/fetch-docs.sh runs it after copying the
# docs; it also runs on its own.
#
#   every line (lts, current, ended)  ->  versions/<wicket>/index.md   (stub page, layout "version")
#   every line with a BOM             ->  _data/availability.yml       (which lines' BOM has which artifact)
#
# The availability data comes from the wicketstuff-bom pom of each line's
# version on Maven Central. A line whose pom can't be downloaded is left out;
# the site then builds without it (and without the availability strip on the
# module pages when no pom could be read).
set -euo pipefail

site="$(cd "$(dirname "$0")/.." && pwd)"
central="${MAVEN_CENTRAL:-https://repo1.maven.org/maven2}"

# One line per release line: <wicket> <version> <bom: true|false> <status: lts|current|ended>
lines="$(awk '
  function flush() { if (wicket != "") print wicket, version, (bom == "false" ? "false" : "true"), status; wicket = version = bom = "" }
  function value(s) { sub(/^[^:]*:[ \t]*/, "", s); sub(/[ \t]+#.*$/, "", s); gsub(/["\047]/, "", s); return s }
  /^releases:/ { r = 1; next }
  r && /^[^ #]/ { flush(); r = 0 }
  !r { next }
  /^  (lts|current|ended):/ { flush(); status = $1; sub(/:$/, "", status); next }
  /^    - / { flush(); sub(/^    - /, "      ") }
  /^ +wicket:/ { wicket = value($0) }
  /^ +version:/ { version = value($0) }
  /^ +bom:/ { bom = value($0) }
  END { flush() }' "$site/_config.yml" | sort -n -k1,1)"

if [ -z "$lines" ]; then
  echo "No release lines under \"releases\" in _config.yml." >&2
  exit 1
fi

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

rm -rf "$site/versions"
mkdir -p "$site/_data"
: > "$tmp/artifacts"
read_lines=()
previous=""

while read -r wicket version bom status; do
  mkdir -p "$site/versions/$wicket"
  {
    echo "---"
    echo "# Generated by scripts/release-lines.sh from releases in _config.yml"
    echo "layout: version"
    echo "title: \"Wicket Stuff $wicket.x\""
    echo "wicket: \"$wicket\""
    [ -n "$previous" ] && echo "previous: \"$previous\""
    echo "---"
  } > "$site/versions/$wicket/index.md"
  previous="$wicket"

  [ "$bom" = "true" ] || continue
  pom="$tmp/bom-$wicket.pom"
  url="$central/org/wicketstuff/wicketstuff-bom/$version/wicketstuff-bom-$version.pom"
  if ! curl -fsSL --retry 3 --max-time 60 -o "$pom" "$url"; then
    echo "Could not download $url; $wicket.x is left out of the availability data." >&2
    continue
  fi
  # groupId:artifactId of every <dependency> in the pom (one tag per line, as Maven writes them).
  awk -v line="$wicket" '
    /<dependency>/ { d = 1; g = a = ""; next }
    d && /<groupId>/ { g = $0; sub(/.*<groupId>[ \t]*/, "", g); sub(/[ \t]*<\/groupId>.*/, "", g) }
    d && /<artifactId>/ { a = $0; sub(/.*<artifactId>[ \t]*/, "", a); sub(/[ \t]*<\/artifactId>.*/, "", a) }
    d && /<\/dependency>/ { d = 0; if (g != "" && a != "") print line, g ":" a }' "$pom" | sort -u > "$tmp/bom-$wicket.txt"
  if [ ! -s "$tmp/bom-$wicket.txt" ]; then
    echo "No dependencies found in $url; $wicket.x is left out of the availability data." >&2
    continue
  fi
  cat "$tmp/bom-$wicket.txt" >> "$tmp/artifacts"
  read_lines+=("$wicket")
  echo "Read $(wc -l < "$tmp/bom-$wicket.txt") artifacts from wicketstuff-bom $version ($wicket.x)."
done <<< "$lines"

{
  echo "# Generated by scripts/release-lines.sh from the wicketstuff-bom poms on Maven Central."
  echo "# lines: the release lines (Wicket major) whose BOM was read, oldest first."
  echo "# artifacts: groupId:artifactId -> the lines whose BOM contains it."
  printf 'lines: ['
  sep=""
  for l in "${read_lines[@]}"; do printf '%s"%s"' "$sep" "$l"; sep=", "; done
  echo "]"
  if [ -s "$tmp/artifacts" ]; then
    echo "artifacts:"
    # Input is sorted by line, oldest first, so each artifact's lines come out in order.
    awk '{ if (!($2 in seen)) { seen[$2] = 1; order[++n] = $2 } in_lines[$2] = in_lines[$2] (in_lines[$2] == "" ? "" : ", ") "\"" $1 "\"" }
      END { for (i = 1; i <= n; i++) print "  \"" order[i] "\": [" in_lines[order[i]] "]" }' "$tmp/artifacts" | sort
  else
    echo "artifacts: {}"
  fi
} > "$site/_data/availability.yml"

echo "Wrote $(echo "$lines" | wc -l) release-line pages and availability data for ${#read_lines[@]} lines."
